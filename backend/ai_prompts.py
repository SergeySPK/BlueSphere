def build_system_prompt() -> str:
    """Возвращает системный промпт текущей версии."""
    return SYSTEM_PROMPT


def build_user_prompt(source: AIAnalysisInput) -> str:
    """
    Формирует пользовательское сообщение из проверенного AI-контекста.

    Вход сериализуется в JSON без потери Unicode.
    Даты преобразуются в ISO-формат средствами Pydantic.
    """
    if not isinstance(source, AIAnalysisInput):
        raise TypeError("source должен быть экземпляром AIAnalysisInput")

    payload = source.model_dump(mode="json")

    serialized_payload = json.dumps(
        payload,
        ensure_ascii=False,
        indent=2,
        sort_keys=True,
    )

    return (
        "Проанализируй учебную нагрузку по следующим данным.\n"
        "Целевая дата анализа: "
        f"{source.target_date.isoformat()}.\n"
        "Период расписания: "
        f"{source.period_start.isoformat()} — "
        f"{source.period_end.isoformat()}.\n\n"
        "ВХОДНЫЕ ДАННЫЕ (JSON):\n"
        f"{serialized_payload}\n\n"
        "Верни результат строго в формате, описанном системным сообщением."
    )
