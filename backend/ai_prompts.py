def build_reference_aliases(source: AIAnalysisInput) -> dict:
    """Создаёт детерминированные псевдонимы вместо реальных ID."""

    teacher_ids = sorted({
        assignment.teacher_id
        for assignment in source.assignments
    })
    assignment_ids = sorted({
        assignment.assignment_id
        for assignment in source.assignments
    })
    schedule_ids = sorted({
        lesson.schedule_id
        for lesson in source.lessons
    })

    return {
        "teachers": {
            teacher_id: f"T{index}"
            for index, teacher_id in enumerate(teacher_ids, start=1)
        },
        "assignments": {
            assignment_id: f"A{index}"
            for index, assignment_id in enumerate(
                assignment_ids,
                start=1,
            )
        },
        "lessons": {
            schedule_id: f"L{index}"
            for index, schedule_id in enumerate(
                schedule_ids,
                start=1,
            )
        },
    }


